object SharePolicy {
    const val SHARING_ENABLED = false

    const val OFF_SUFFIX = " · вимкнено"

    const val OFF_MESSAGE =
        "У Renodocs передавати томи й проєкти іншим вимкнено автором. " +
            "Імпорт і читання працюють, як раніше."

    fun title(title: String): String =
        if (SHARING_ENABLED) title else title + OFF_SUFFIX
}
