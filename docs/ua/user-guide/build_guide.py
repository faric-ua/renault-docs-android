def inline_html(text):
    # text is trusted authored content with <b> tags; escape everything else.
    parts = re.split(r"(</?b>)", text)
    return "".join(p if p in ("<b>", "</b>") else html.escape(p, quote=False) for p in parts)


def to_md_inline(text):
    return text.replace("<b>", "**").replace("</b>", "**")


def build_html():
    toc = "\n".join(f'<li><a href="#{sid}">{html.escape(title)}</a></li>' for sid, title, _ in S)
    body = []
    for sid, title, blocks in S:
        out = [f'<section id="{sid}"><h2>{html.escape(title)}</h2>']
        for kind, val in blocks:
            if kind == "p":
                out.append(f"<p>{inline_html(val)}</p>")
            elif kind == "ul":
                out.append("<ul>" + "".join(f"<li>{inline_html(i)}</li>" for i in val) + "</ul>")
            elif kind == "note":
                out.append(f'<p class="note">{inline_html(val)}</p>')
            elif kind == "mermaid":
                out.append(f'<div class="diagram"><pre class="mermaid">{html.escape(val, quote=False)}</pre></div>')
        out.append("</section>")
        body.append("\n".join(out))
    tpl = Path(sys.argv[1]).read_text(encoding="utf-8")
    return (tpl.replace("{{TOC}}", toc)
               .replace("{{BODY}}", "\n".join(body))
               .replace("{{VERSION}}", VERSION)
               .replace("{{DATE}}", DATE))


def build_md():
    lines = [f"# Посібник Renault Docs", "",
             f"_Для користувача. Версія застосунку {VERSION}, {DATE}. Схеми — Mermaid (GitHub показує їх як картинки)._", "",
             "Цей самий посібник файлами: [Word](Posibnyk-Renault-Docs.docx) · [PDF](Posibnyk-Renault-Docs.pdf). Перезібрати всі формати: `docs/ua/user-guide/build.sh`.", ""]
    for sid, title, _ in S:
        lines.append(f"- [{title}](#{sid})")
    lines.append("")
    for sid, title, blocks in S:
        lines += [f'<a id="{sid}"></a>', f"## {title}", ""]
        for kind, val in blocks:
            if kind == "p":
                lines += [to_md_inline(val), ""]
            elif kind == "ul":
                lines += [f"- {to_md_inline(i)}" for i in val] + [""]
            elif kind == "note":
                lines += [f"> {to_md_inline(val)}", ""]
            elif kind == "mermaid":
                lines += ["```mermaid", val, "```", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    out_dir = Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "renault-docs-guide.html").write_text(build_html(), encoding="utf-8")
    (out_dir / "USER_GUIDE.md").write_text(build_md(), encoding="utf-8")
    print("ok", len(S), "sections")
